const axios = require('axios');
const store = require('../services/store');

const ML_SERVICE_URL = process.env.ML_SERVICE_URL || 'http://localhost:5001';

/**
 * Submit new assessment
 * POST /api/predictions
 */
const submitPrediction = async (req, res) => {
  const formData = req.body || {};
  const userId = req.user?.id || req.user?._id || 'usr_guest';

  // Calculate BMI if missing
  let bmi = formData.bmi;
  if (!bmi && formData.heightCm && formData.weightKg) {
    const h = Number(formData.heightCm) / 100.0;
    const w = Number(formData.weightKg);
    if (h > 0 && w > 0) {
      bmi = parseFloat((w / (h * h)).toFixed(1));
    }
  }

  const measurements = {
    ...formData,
    bmi,
  };

  const assessmentId = `DRP-${new Date().getFullYear()}-${Math.floor(1000 + Math.random() * 9000)}`;

  let mlResponse = null;
  let serviceConnected = false;

  try {
    // Forward to Flask Machine Learning service on port 5001
    const response = await axios.post(
      `${ML_SERVICE_URL}/predict`,
      { features: measurements },
      { timeout: 6000 }
    );

    if (response.data && response.data.success) {
      mlResponse = response.data;
      serviceConnected = true;
    }
  } catch (err) {
    console.warn(`[ML Service] Could not connect to ML service at ${ML_SERVICE_URL}:`, err.message);
  }

  const assessmentRecord = {
    id: assessmentId,
    assessmentId,
    userId,
    createdAt: new Date().toISOString(),
    status: serviceConnected ? 'Completed' : 'Awaiting Prediction Service',
    serviceConnected,
    measurements,
    predictionResult: serviceConnected
      ? {
          prediction: mlResponse.prediction,
          classification: mlResponse.classification,
          estimatedProbability: mlResponse.estimatedProbability,
          probabilities: mlResponse.probabilities,
          summary: mlResponse.summary,
          modelVersion: mlResponse.modelVersion,
          modelType: mlResponse.modelType,
          message: mlResponse.message || 'Educational prediction generated by scikit-learn model.',
          educationalDisclaimer:
            mlResponse.educationalDisclaimer ||
            'This tool is for educational purposes only and cannot diagnose diabetes.',
        }
      : null,
  };

  await store.createAssessment(assessmentRecord);

  res.status(200).json(assessmentRecord);
};

/**
 * Retrieve assessments
 * GET /api/predictions
 */
const getPredictions = async (req, res) => {
  try {
    const userId = req.user?.id || req.user?._id || null;
    let records = await store.getAssessments(userId);

    const { search, riskLevel } = req.query;

    if (search) {
      const q = search.toLowerCase();
      records = records.filter(
        (r) =>
          r.id?.toLowerCase().includes(q) ||
          r.predictionResult?.classification?.toLowerCase().includes(q) ||
          r.predictionResult?.summary?.toLowerCase().includes(q)
      );
    }

    if (riskLevel) {
      records = records.filter((r) => {
        const cls = r.predictionResult?.classification?.toLowerCase() || '';
        return cls.includes(riskLevel.toLowerCase());
      });
    }

    res.status(200).json(records);
  } catch (err) {
    console.error('Error fetching predictions:', err);
    res.status(500).json({ message: 'Error retrieving assessment history.' });
  }
};

/**
 * Get assessment by ID
 * GET /api/predictions/:id
 */
const getPredictionById = async (req, res) => {
  try {
    const { id } = req.params;
    const record = await store.getAssessmentById(id);

    if (!record) {
      return res.status(404).json({ message: 'Assessment record not found.' });
    }

    res.status(200).json(record);
  } catch (err) {
    console.error('Error fetching assessment by id:', err);
    res.status(500).json({ message: 'Error retrieving assessment.' });
  }
};

/**
 * Delete assessment by ID
 * DELETE /api/predictions/:id
 */
const deletePrediction = async (req, res) => {
  try {
    const { id } = req.params;
    await store.deleteAssessment(id);
    res.status(200).json({ success: true, message: 'Assessment record deleted.' });
  } catch (err) {
    console.error('Error deleting assessment:', err);
    res.status(500).json({ message: 'Error deleting assessment.' });
  }
};

module.exports = {
  submitPrediction,
  getPredictions,
  getPredictionById,
  deletePrediction,
};
